function csvEscape(value) {
  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function makeCsv(headers, data) {
  return [
    headers.join(","),
    ...data.map((row) => headers.map((_, index) => csvEscape(row[index])).join(",")),
  ].join("\n");
}

